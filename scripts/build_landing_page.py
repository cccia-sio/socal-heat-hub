"""Build the GitHub Pages landing page (index.html).

The "Data sources" section is one dropdown per pillar, derived from the
viewer's VARIABLES / VAR_SOURCES / SOURCE_NAMES tables so the public site
can't advertise a source the map no longer uses. Everything else is static
copy in HTML_TEMPLATE below; never edit index.html directly.

Usage:
    python scripts/build_landing_page.py

Output:
    index.html
"""

import sys
from collections import Counter
from html import escape
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from build_diy_pca_viewer import (  # noqa: E402
    FUTURE_PERIODS,
    HEAT_MODES,
    SOURCE_NAMES,
    SSP_LABELS,
    VAR_SOURCES,
    VARIABLES,
)

ROOT = Path(__file__).resolve().parent.parent
OUTPUT_PATH = ROOT / "index.html"

# (VARIABLES pillar key, CSS class shared with the pillar cards, label)
PILLARS = [
    ("exposure", "exp", "Exposure"),
    ("sensitivity", "sen", "Sensitivity"),
    ("adaptive", "ada", "Adaptive Capacity"),
]

# LOCA2 isn't a VARIABLES source: compute_tract_deltas() applies its warming
# deltas to the exposure layers for the future scenarios, so it's listed here.
LOCA2_URL = "https://loca.ucsd.edu/"


def source_groups():
    """Per pillar, the viewer's sources, most variables first: [(name, url, n_vars)]."""
    groups = []
    for key, *_ in PILLARS:
        counts = Counter(VAR_SOURCES[v[0]] for v in VARIABLES if v[2] == key)
        groups.append((key, [(SOURCE_NAMES[url], url, n) for url, n in counts.most_common()]))
    return groups


def _plural(n, word):
    return f"{n} {word}{'s' if n != 1 else ''}"


def render_sources():
    blocks = []
    for (key, cls, label), (_, rows) in zip(PILLARS, source_groups()):
        items = [
            f'          <li><a href="{escape(url)}">{escape(name)}</a> &middot; {_plural(n, "variable")}</li>'
            for name, url, n in rows
        ]
        note = ""
        if key == "exposure":
            modes = [m[1][0].lower() + m[1][1:] for m in HEAT_MODES]
            note = (
                '\n        <p class="src-note">The map shows one heat mode at a time: '
                f"{escape(', '.join(modes[:-1]))}, or {escape(modes[-1])}.</p>"
            )
            items.append(
                f'          <li><a href="{LOCA2_URL}">LOCA2 downscaled CMIP6</a> &middot; climate projections for '
                f"{' and '.join(FUTURE_PERIODS)} ({escape(', '.join(SSP_LABELS.values()))})</li>"
            )
        n_vars = sum(n for *_, n in rows)
        blocks.append(f"""      <details class="src {cls}">
        <summary><h3>{escape(label)}</h3><span class="src-count">{_plural(len(items), "source")} &middot; {_plural(n_vars, "variable")}</span></summary>{note}
        <ul>
{chr(10).join(items)}
        </ul>
      </details>""")
    return "\n".join(blocks)


def render():
    return HTML_TEMPLATE.replace("__SOURCES_PLACEHOLDER__", render_sources())


def main():
    OUTPUT_PATH.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(ROOT)}")


